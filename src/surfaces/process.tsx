/**
 * ERP Process Floor — the Phase 4 surface.
 *
 * WHAT IT ANSWERS
 *
 * What does canonical process truth say about the five business-process
 * families, stage by stage, and what is the declared blocker on each. That is
 * the convergence question, and it is a different question from Phase 2's "is
 * the control plane healthy" and Phase 3's "who is working on what".
 *
 * SEVEN SEPARATIONS THIS SURFACE ENFORCES
 *
 *   1. ACTIVITY IS NOT MATURITY, AND THE JOIN KEY IS ABSENT BY DESIGN.
 *      `activity.json` carries a `process_stage` field and it is null on every
 *      event in the live window. This surface therefore holds no agent column,
 *      no event count and no work attribution of any kind. The absence is the
 *      guarantee: a stage cannot be advanced by anything that happens on the
 *      floor, because nothing on the floor is connected to a stage.
 *
 *   2. `family.maturity` IS PROSE, NOT A SCORE. Canonical source writes
 *      "critical-path", "least-complete", "working-ledger-missing-spine". Those
 *      are descriptive labels about structure. They are rendered as the words
 *      they are — never scored, never ranked, never sorted on, never turned
 *      into a percentage or a comparison.
 *
 *   3. FAMILY STATE IS THE WORST STAGE, NEVER AN AVERAGE. A family with ten
 *      implemented stages and one absent stage is a family with an absent
 *      stage. The rollup is an order-based selection over declared states; no
 *      arithmetic is performed on the states themselves.
 *
 *   4. `stage.evidence` IS NOT RENDERED AS EVIDENCE. Canonical `evidence[]` is
 *      generated by regex-scraping backtick spans out of roadmap prose, so its
 *      entries are a mix of Room sequence numbers, bare filenames, prose
 *      fragments and truncated strings. Measured: 0 of 37 resolve as a ledger
 *      event id, 27 of 49 stages carry none, and 20 are the same pointer listed
 *      twice with a stray backtick. Presenting those as verified citations
 *      would assert a provenance that does not exist. The `note` field IS
 *      rendered, because it is canonical roadmap prose written for a reader,
 *      and it is labelled as a note rather than as proof.
 *
 *   5. NO PER-STAGE RECONCILIATION IS RENDERED. The five reconciliation
 *      invariants are "documented intent only" and not executable (G3 /
 *      SERP-461, planned). The surface says so once, in the constraints rail,
 *      rather than drawing a reconciliation column that would imply a
 *      reconciled control relationship nobody has executed.
 *
 *   6. NO 13-DIMENSION MATRIX. The process-level definition of done names
 *      thirteen evidence dimensions, but no canonical field records, for any
 *      stage, whether any of them was proven. A 49x13 grid would be 637 cells
 *      of nothing rendered as though it were assurance.
 *
 *   7. UNKNOWN IS NOT COERCED. A family with no stages, a stage with no
 *      blocker, a state the source does not record — each renders as UNKNOWN
 *      rather than defaulting to the nearest healthy-looking value.
 *
 * THIS COMPONENT COMPUTES NO BUSINESS TRUTH
 *
 * Every stage state, family label and blocker arrives verbatim from canonical
 * process truth. The only computation in this file is `worstStage()`, an
 * order-based selection over the declared severity ordering that already
 * existed in `lib/states.ts` for the Phase 1 overview strip. There is no
 * scoring, no weighting, no percentage, no ratio and no clock here — and that
 * is asserted by test rather than by intention.
 */

/** Worst-first, matching the canonical severity ordering in lib/states.ts. */
const WORST_LABEL = 'WORST STAGE';

/** The states canonical source declares, in severity order, for the legend. */
const DECLARED_STATES: StageState[] = [
  'implemented',
  'partial',
  'test-only',
  'schema-only',
  'absent',
  'UNKNOWN',
];

function chip(tone: string | undefined): string {
  return cn(
    'inline-flex shrink-0 items-center rounded border px-1.5 py-0.5 font-mono text-2xs uppercase tracking-wider',
    tone ?? 'bg-truth-unknown-soft text-truth-unknown border-truth-unknown/30',
  );
}

function SerpRefs({ refs }: { refs: string[] }) {
  if (!refs.length) {
    return <UnknownValue label="NO TASK REF" reason="canonical source records no SERP reference on this stage" />;
  }
  return (
    <span className="flex flex-wrap gap-1">
      {refs.map((r) => (
        <span
          key={r}
          className="rounded border border-border bg-surface-0/40 px-1 py-px font-mono text-2xs text-muted-foreground"
        >
          {r}
        </span>
      ))}
    </span>
  );
}

function StageTable({ stages }: { stages: Stage[] }) {
  return (
    <Table>
      <TableHeader>
        <TableRow>
          <TableHead className="w-[26%]">Stage</TableHead>
          <TableHead className="w-[15%]">Canonical state</TableHead>
          <TableHead className="w-[20%]">SERP ref (metadata only)</TableHead>
          <TableHead className="w-[13%]">Blocked by</TableHead>
          <TableHead>Canonical note (prose, not proof)</TableHead>
        </TableRow>
      </TableHeader>
      <TableBody>
        {stages.map((s) => {
          const tone = STAGE_TONE[s.state] ?? STAGE_TONE.UNKNOWN;
          return (
            <TableRow key={s.stage}>
              <TableCell className="font-medium text-foreground">{s.stage}</TableCell>
              <TableCell>
                <span className={chip(tone.chip)}>{tone.label}</span>
              </TableCell>
              <TableCell>
                <SerpRefs refs={s.serp ?? []} />
              </TableCell>
              <TableCell>
                {s.blocked_by ? (
                  <span className="font-mono text-2xs text-truth-founder">{s.blocked_by}</span>
                ) : (
                  <UnknownValue label="NOT BLOCKED" reason="canonical source records no blocker on this stage" />
                )}
              </TableCell>
              <TableCell className="text-2xs text-muted-foreground">{s.note ?? 'UNKNOWN'}</TableCell>
            </TableRow>
          );
        })}
      </TableBody>
    </Table>
  );
}

function FamilyCard({ family }: { family: ProcessFamily }) {
  // Order-based selection over declared states. Not an average, not a score.
  const worst = worstStage(family.stages.map((s) => s.state));
  const tone = STAGE_TONE[worst] ?? STAGE_TONE.UNKNOWN;

  return (
    <Card>
      <CardHeader>
        <div className="flex flex-wrap items-start gap-3">
          <div className="min-w-0 flex-1">
            <div className="flex items-center gap-2">
              <span className="font-mono text-2xs uppercase tracking-wider text-muted-foreground">
                {family.id}
              </span>
              <CardTitle className="text-base">{family.name}</CardTitle>
            </div>
            <CardDescription className="mt-1">
              {family.headline ?? 'No headline recorded in canonical source'}
            </CardDescription>
          </div>
          <div className="flex flex-col items-end gap-1">
            <span className="label-micro">{WORST_LABEL}</span>
            <span className={cn(chip(tone.chip), 'text-xs')}>{tone.label}</span>
          </div>
        </div>
      </CardHeader>
      <CardContent className="space-y-3">
        <div className="grid gap-3 sm:grid-cols-3">
          <div className="min-w-0">
            <p className="label-micro">Declared maturity (prose)</p>
            <p className="mt-0.5 text-2xs text-foreground/90">
              {family.maturity ? (
                family.maturity
              ) : (
                <UnknownValue reason="canonical source records no maturity label for this family" />
              )}
            </p>
            <p className="mt-0.5 text-2xs text-muted-foreground/70">
              Descriptive label from canonical source. Not scored, not ranked.
            </p>
          </div>
          <div className="min-w-0">
            <p className="label-micro">Critical blocker</p>
            <p className="mt-0.5 font-mono text-2xs text-truth-founder">
              {family.critical_blocker ?? (
                <UnknownValue reason="canonical source records no critical blocker" />
              )}
            </p>
          </div>
          <div className="min-w-0">
            <p className="label-micro">Stages classified</p>
            <p className="tnum mt-0.5 text-2xs text-foreground/90">
              {formatCount(family.stages.length)}
            </p>
            <p className="mt-0.5 text-2xs text-muted-foreground/70">
              Count of canonical classifications. A count is not a completion figure.
            </p>
          </div>
        </div>

        <Separator />

        <StageTable stages={family.stages} />
      </CardContent>
    </Card>
  );
}

/**
 * The honesty rail. Every line is a condition that would silently corrupt the
 * reading of this surface if it were smoothed over.
 */
function ConstraintsRail({
  evidenceStages,
  invariantState,
  implementation,
}: {
  evidenceStages: number;
  invariantState: string | null;
  implementation: string;
}) {
  const implementationNote = implementation === 'RESTART_AUTHORIZED'
    ? 'The current canonical decision authorizes StarqERP implementation. Active task execution and acceptance are sourced separately.'
    : implementation === 'ON_HOLD'
      ? 'StarqERP implementation is on hold in the current canonical decision. This surface does not schedule work.'
      : 'Current StarqERP implementation authorization is UNKNOWN. This surface does not infer it.';
  const constraints: { icon: typeof Scale; text: string }[] = [
    {
      icon: Scale,
      text: 'Raw SERP task completion is not ERP maturity. A closed ticket, an applied migration or a green CI run is evidence of work, not of a business process.',
    },
    {
      icon: ShieldAlert,
      text: 'A merged module or a passing test is evidence, not maturity. A stage is only as complete as canonical process truth says it is.',
    },
    {
      icon: AlertTriangle,
      text: `Evidence drill-down is unavailable in this phase. Canonical evidence[] is generator-derived metadata and is not rendered as verified or openable evidence. ${formatCount(evidenceStages)} of 49 stages carry an evidence entry at all.`,
    },
    {
      icon: AlertTriangle,
      text: `Per-stage reconciliation is unavailable in this phase. The five control invariants are recorded as${
        invariantState ? ` "${invariantState}"` : ' unrecorded'
      } and are not rendered as a reconciled state.`,
    },
    {
      icon: Boxes,
      text: 'Process state is independent of execution activity. The execution ledger carries no stage key, so nothing on the Dev Studio Floor can advance or explain a stage here.',
    },
    {
      icon: Lock,
      text: implementationNote,
    },
  ];

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-sm">
          <GitBranch className="h-4 w-4 text-truth-founder" />
          How to read this floor
        </CardTitle>
        <CardDescription>
          These constraints are not disclaimers. Each one is a place where a
          plausible-looking reading would be false.
        </CardDescription>
      </CardHeader>
      <CardContent>
        <ul className="space-y-2">
          {constraints.map((c) => (
            <li key={c.text} className="flex gap-2 text-2xs text-muted-foreground">
              <c.icon className="mt-0.5 h-3 w-3 shrink-0 text-truth-founder" />
              <span>{c.text}</span>
            </li>
          ))}
        </ul>
      </CardContent>
    </Card>
  );
}

/** The classification legend. Renders states that do not occur today too. */
function ClassificationLegend({ key_ }: { key_: Record<string, string> }) {
  const states = DECLARED_STATES.filter((s) => key_[s]);
  if (!states.length) return null;

  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-sm">Stage classification key</CardTitle>
        <CardDescription>
          Declared by canonical source. States that do not occur today are still
          shown, so the vocabulary stays legible on the day one of them does.
        </CardDescription>
      </CardHeader>
      <CardContent>
        <ul className="grid gap-2 sm:grid-cols-2">
          {states.map((s) => (
            <li key={s} className="flex flex-col gap-0.5">
              <span className={chip(STAGE_TONE[s].chip)}>{STAGE_TONE[s].label}</span>
              <span className="text-2xs text-muted-foreground">{key_[s]}</span>
            </li>
          ))}
        </ul>
      </CardContent>
    </Card>
  );
}

function RestartCard({ surface }: { surface: CommandSurface }) {
  const pt = surface.process_truth;
  const hold = pt.hold_state ?? null;
  const wave = pt.restart_wave_after_authorization ?? [];
  const authorized = hold?.implementation === 'RESTART_AUTHORIZED';
  const onHold = hold?.implementation === 'ON_HOLD';
  const authorizationLabel = hold?.implementation ?? 'UNKNOWN';

  return (
    <Card>
      <CardHeader>
        <div className="flex flex-wrap items-center gap-2">
          <CardTitle className="flex items-center gap-2 text-sm">
            {onHold ? <Lock className="h-4 w-4 text-truth-hold" /> : null}
            ERP implementation state
          </CardTitle>
          <Badge
            variant="outline"
            className={authorized
              ? 'border-truth-founder/40 bg-truth-founder-soft text-truth-founder'
              : onHold
                ? 'border-truth-hold/40 bg-truth-hold-soft text-truth-hold'
                : 'border-truth-unknown/40 bg-truth-unknown-soft text-truth-unknown'}
          >
            {authorizationLabel}
          </Badge>
        </div>
        <CardDescription>
          {authorized
            ? 'Canonical source authorizes the implementation sequence. This does not prove task execution, acceptance or a schedule.'
            : onHold
              ? 'Canonical source records ON_HOLD. This surface does not schedule work.'
              : 'Current implementation authorization is UNKNOWN; no status is inferred.'}
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-3">
        {!hold ? (
          <UnknownValue
            reason="canonical contract carries no implementation authorization state"
          />
        ) : (
          /*
            R4. Authority, Effective and restart requirement are the canonical implementation decision
            record, and HoldBanner renders all three above this card on every
            ERP tab. They are removed here rather than restated.

            What stays is genuinely local to this surface and cannot be carried
            by a one-line banner:
              · hold.reason        — the narrative rationale, per-surface detail
              · the restart sequence basis — an ordered list, which a banner cannot hold
            The gate-conditions heading is also promoted to .label-sec: it is a
            group heading introducing several rows, which is exactly the middle
            rung of the h2 -> label-sec -> label-micro ladder (R5).
          */
          <>
            <p className="text-2xs text-muted-foreground">{hold.reason}</p>
            {hold.restart_gate_conditions?.length ? (
              <div>
                <p className="label-sec mb-1">Restart authorization basis</p>
                <ul className="space-y-1">
                  {hold.restart_gate_conditions.map((g) => (
                    <li key={g} className="flex gap-2 text-2xs text-muted-foreground">
                      <span className="mt-1.5 h-0.5 w-0.5 shrink-0 rounded-full bg-truth-hold" />
                      {g}
                    </li>
                  ))}
                </ul>
              </div>
            ) : (
              <p className="text-2xs text-muted-foreground">
                {authorized
                  ? 'DEC-109 authorizes the implementation sequence; task execution remains separately sourced.'
                  : 'No restart authorization basis is recorded in canonical source.'}
              </p>
            )}
          </>
        )}

        <Separator />

        <div>
          <div className="mb-1 flex items-center gap-2">
            <p className="label-sec">Implementation sequence (declared order)</p>
            <Badge variant="outline" className={authorized
              ? 'border-truth-founder/40 bg-truth-founder-soft text-truth-founder'
              : onHold
                ? 'border-truth-hold/40 bg-truth-hold-soft text-truth-hold'
                : 'border-truth-unknown/40 bg-truth-unknown-soft text-truth-unknown'}>
              {authorizationLabel}
            </Badge>
          </div>
          {!wave.length ? (
            <UnknownValue reason="canonical contract records no restart wave" />
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead className="w-[8%]">#</TableHead>
                  <TableHead className="w-[18%]">Task</TableHead>
                  <TableHead className="w-[34%]">Title</TableHead>
                  <TableHead>Nature</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {wave.map((w) => (
                  <TableRow key={`${w.order}-${w.task}`}>
                    <TableCell className="tnum font-mono text-2xs text-muted-foreground">
                      {String(w.order ?? '?')}
                  </TableCell>
                    <TableCell className="font-mono text-2xs text-truth-founder">
                      {String(w.task ?? 'UNKNOWN')}
                    </TableCell>
                    <TableCell className="text-2xs text-foreground/90">{String(w.title ?? 'UNKNOWN')}</TableCell>
                    <TableCell className="text-2xs text-muted-foreground">
                      {String(w.nature ?? 'UNKNOWN')}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          )}
          <p className="mt-2 text-2xs text-muted-foreground/80">
            {authorized
              ? 'Canonical source authorizes this sequence. Its order is not a schedule, and it does not prove that any task is executing.'
              : onHold
                ? 'Canonical source records ON_HOLD. This sequence is NOT AUTHORISED to proceed.'
                : 'Canonical source does not establish whether this sequence is authorized.'}
            {' This surface does not authorise, imply or schedule any restart.'}
          </p>
        </div>
      </CardContent>
    </Card>
  );
}

function DiscrepanciesCard({ surface }: { surface: CommandSurface }) {
  const d = surface.process_truth.reconciliation?.known_discrepancies ?? [];
  if (!d.length) return null;

  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-sm">Carried discrepancies</CardTitle>
        <CardDescription>
          Recorded by canonical source as unresolved. Command surfaces them and
          never reconciles them.
        </CardDescription>
      </CardHeader>
      <CardContent>
        <ul className="space-y-2">
          {d.map((x) => (
            <li
              key={x.id}
              className="rounded-md border border-truth-founder/30 bg-truth-founder-soft/30 px-3 py-2"
            >
              <div className="flex items-center gap-2">
                <span className="font-mono text-2xs text-truth-founder">{x.id}</span>
                <span className="text-2xs font-medium text-foreground/90">{x.item}</span>
                {x.founder_decision_required ? (
                  <Badge
                    variant="outline"
                    className="ml-auto border-truth-founder/40 text-truth-founder"
                  >
                    FOUNDER DECISION
                  </Badge>
                ) : null}
              </div>
              <p className="mt-1 text-2xs text-muted-foreground">{x.resolution}</p>
            </li>
          ))}
        </ul>
      </CardContent>
    </Card>
  );
}

export function ProcessSurface({ surface }: { surface: CommandSurface }) {
  const pt = surface.process_truth;

  if (!pt.available) {
    return (
      <div className="p-4">
        <UnknownValue
          label="PROCESS TRUTH UNAVAILABLE"
          reason={
            pt.reason ??
            'Canonical process truth could not be read. The process floor refuses to render an empty-but-healthy surface.'
          }
        />
      </div>
    );
  }

  const families = pt.process_families ?? [];
  const evidenceStages = families.reduce(
    (n, f) => n + f.stages.filter((s) => (s.evidence ?? []).length > 0).length,
    0,
  );
  const totalStages = families.reduce((n, f) => n + f.stages.length, 0);

  return (
    <div className="flex flex-col gap-4 p-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
              <div>
                {/*
                  The same DUPLICATE PAGE TITLE defect I fixed on Founder Attention,
                  found by the same browser probe: RoomHead already renders an h1
                  ("starqERP") for every ERP peer, and this block rendered a second
                  one 300px below it. The room head owns the page title; this keeps
                  the descriptor line, which is the actual content here.
                */}
                <p className="tier-answer">
                  ERP Process Floor — {formatCount(families.length)} canonical process families ·{' '}
                  {formatCount(totalStages)} stage classifications · parsed from the canonical roadmap,
                  never re-derived
                </p>
              </div>
        <div className="text-right">
          <p className="label-micro">Canonical projection generated</p>
          <p className="font-mono text-2xs text-muted-foreground">
            {formatTimestamp(pt.generated_at)}
          </p>
        </div>
      </div>

      <ConstraintsRail
        evidenceStages={evidenceStages}
        invariantState={
          (pt.reconciliation_invariants_pending?.state as string | undefined) ?? null
        }
        implementation={pt.hold_state?.implementation ?? 'UNKNOWN'}
      />

      <ClassificationLegend key_={pt.stage_classification_key ?? {}} />

      {families.map((f) => (
        <FamilyCard key={f.id} family={f} />
      ))}

      <RestartCard surface={surface} />
      <DiscrepanciesCard surface={surface} />
    </div>
  );
}
