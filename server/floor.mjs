const CANONICAL_HERDR_MANIFEST = CANONICAL.herdrManifest;

// Staff-glance groups use only exact source tokens. These match the Staff
// surface's declared-status filters; source values such as ACTIVE, OFFLINE and
// AVAILABLE are not translated into another duty state. A row may appear in
// more than one named group when duty and execution disagree, just as it does
// in the two independent roster filters. `unknown` is the complement: no
// declared value matched any named group.
const STAFF_GLANCE_STATUS_TOKENS = Object.freeze({
  working: ['WORKING', 'Working'],
  idle: ['IDLE', 'Idle'],
  blocked: ['BLOCKED', 'Blocked'],
  awaiting_review: ['AWAITING_REVIEW', 'Awaiting review', 'AWAITING REVIEW'],
  unavailable: ['UNAVAILABLE', 'Unavailable'],
});

export function computeStaffGlanceCounts(rosterEntries) {
  const groups = Object.entries(STAFF_GLANCE_STATUS_TOKENS);
  const counts = {
    working: 0,
    idle: 0,
    blocked: 0,
    awaiting_review: 0,
    unavailable: 0,
    unknown: 0,
  };

  for (const entry of rosterEntries) {
    const declared = [entry.duty_state, entry.current_state].map((value) =>
      typeof value === 'string' ? value.trim() : '',
    );
    let matched = false;
    for (const [group, tokens] of groups) {
      if (declared.some((value) => tokens.includes(value))) {
        counts[group] += 1;
        matched = true;
      }
    }
    if (!matched) counts.unknown += 1;
  }

  return counts;
}

/**
 * THE CANONICAL TEN, AND WHAT IS NOT IN THEM
 *
 * `roster.entries` is every handle the execution ledger observes, and it always
 * will be — an entry is evidence and dropping evidence is how a surface starts
 * lying. What changed is that each entry now says whether it is one of the ten
 * canonical Dev Studio seats, and the MAIN STAFF SURFACE renders only those.
 *
 * Two separate things are being kept apart here, and merging them would undo
 * the fix:
 *
 *   1. The roster is COMPLETE. `roster.entries.length` still equals the observed
 *      agent population, because that number is what makes "this surface is
 *      hiding 12 people" auditable.
 *   2. The main staff surface is CURATED. `floor.staff.canonical_seats` is the
 *      ten, joined; `floor.staff.suppressed` carries the rest with a reason
 *      each and a count, so suppression is stated rather than silent.
 *
 * A suppression is a presentation ruling, not a deletion and not a retirement.
 * Nothing here can retire a handle, revoke an identity, or reclassify staff —
 * those remain canonical-source facts, forwarded verbatim.
 */

/**
 * The signal filter, exactly as the Founder specified it.
 *
 * These four flags are the canonical "this event says something" markers. An
 * event carrying any of them is meaningful regardless of who sent it — a
 * machine-generated post carrying real evidence is signal, not noise.
 */
export const SIGNAL_FLAGS = Object.freeze(['has_evidence', 'is_blocker', 'is_handoff', 'needs_founder']);

/** Does this event carry at least one signal flag? */
export function carriesSignal(event) {
  if (!event || typeof event !== 'object') return false;
  return SIGNAL_FLAGS.some((flag) => event[flag] === true);
}

/** The canonical classification vocabulary, kept literal so an unknown value is visible. */
export const CLASSIFICATION = Object.freeze({
  STAFF: 'STAFF',
  SYSTEM: 'SYSTEM',
  RETIRED: 'RETIRED',
  UNKNOWN: 'UNKNOWN',
});

function unknown(v) {
  return v === null || v === undefined || v === '' || v === 'UNKNOWN';
}

