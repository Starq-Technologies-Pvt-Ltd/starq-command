/**
 * Resolve one roster row. *
 * `counts_as_active_staff` and `staff_classification` are forwarded, not
 * computed — but the ROSTER GROUPS are computed, because grouping is a
 * presentation concern and a component doing it would need exactly the same
 * canonical fields to do it safely. The dangerous field is the one that must
 * never be inferred: an agent is retired because canonical source says so, and
 * for a handle with no canonical identity we say UNKNOWN rather than guessing.
 */
function buildRosterEntry({ agent, identity, staff, session, conflictTypes, herdrSeat }) {
  const handle = agent.handle;
  const classification = agent.staff_classification ?? CLASSIFICATION.UNKNOWN;

  // Retirement is asserted by canonical source only. `nexus` is RETIRED in
  // both the identity registry and the staff record; nothing in this function
  // can promote, demote or reclassify a handle.
  const isRetired = classification === CLASSIFICATION.RETIRED || identity?.status === 'retired';

  // Active staff requires canonical corroboration, not absence of a flag.
  // An agent with no identity record is NOT counted active: `hermes` appears in
  // the execution ledger with no canonical identity, and rendering it as staff
  // would be inventing an identity.
  const isActiveStaff =
    classification === CLASSIFICATION.STAFF && agent.counts_as_active_staff === true && !isRetired;

  const executionTask = unknown(agent.current_task) ? null : agent.current_task;
  const dutyTask = staff && !unknown(staff.duty_current_task) ? staff.duty_current_task : null;

  // An EMPTY STRING is a value, not an absence, and rendering one produces a
  // blank cell that reads as "nothing to report" rather than "canonical source
  // records no role". `hermes` carries `identity_role: ""` and
  // `identity_status: "UNKNOWN"` in the live ledger — it is observed in
  // execution with no canonical identity record, and every field about it must
  // say so rather than showing an empty column.
  const role = identity?.role || agent.identity_role || null;

  // ── Seat-profile join ────────────────────────────────────────────────────
  //
  // The profile is DECLARED metadata keyed by Room handle. A handle with no
  // profile row is not "unknown provider" — it is not a seat, and saying so is
  // the entire point of the curation.
  const isCanonicalSeat = isCanonicalStaffHandle(handle);
  const profile = isCanonicalSeat ? staffProfileFor(handle) : null;

  // ── Herdr join ───────────────────────────────────────────────────────────
  //
  // DECLARED launch facts only, and only where the seat actually names a
  // manifest row. `copilot` and `opencode` have none, and the floor reports the
  // absence instead of guessing an id.
  //
  // The host conflict is REPORTED, not resolved. Elder is declared WSL by the
  // Founder roster and WINDOWS by the Herdr manifest, and which of those is
  // canonical is a Founder decision that no line in this file is entitled to
  // make. Recording `values_differ` is the honest shape.
  const herdr = profile
    ? herdrSeat
      ? {
          declared: true,
          seat_id: herdrSeat.seat_id,
          declared_runtime: herdrSeat.declared_runtime,
          launchable: herdrSeat.launchable,
          startup_policy: herdrSeat.startup_policy,
          terminal: herdrSeat.terminal,
          executable_present: herdrSeat.executable_present,
          identity_probe: herdrSeat.identity_probe,
          herdr_kind: herdrSeat.herdr_kind,
          evidence: herdrSeat.evidence,
        }
      : {
          declared: false,
          seat_id: profile.herdr_seat_id,
          declared_runtime: null,
          launchable: null,
          startup_policy: null,
          terminal: null,
          executable_present: null,
          identity_probe: null,
          herdr_kind: null,
          evidence: null,
          absent_reason: profile.herdr_seat_id
            ? `the Herdr manifest declares no row for seat id "${profile.herdr_seat_id}"`
            : 'the staff profile declares no Herdr seat id for this handle',
        }
    : null;

  // Compared as a plain string inequality, exactly like the two current_task
  // truths above. No normalisation: "WSL" and "wsl" are the same host, but this
  // function is not entitled to decide that they are, and a false conflict here
  // costs one extra line on screen while a false agreement would cost a seat.
  const herdrHostConflict = Boolean(
    herdr?.declared && profile?.normal_host &&
      String(herdr.declared_runtime).toUpperCase() !== String(profile.normal_host).toUpperCase(),
  );

  return {
    handle,
    // ── Canonical identity (never invented) ──────────────────────────────
    identity_present: Boolean(identity),
    identity_status: identity?.status ?? 'UNKNOWN',
    display_name: identity?.display_name ?? null,
    role,
    authority_level: identity?.authority_level ?? null,
    is_legacy: Boolean(identity?.is_legacy),
    is_revoked: Boolean(identity?.is_revoked),

    // ── Staff classification (never inferred) ─────────────────────────────
    staff_classification: classification,
    counts_as_active_staff: agent.counts_as_active_staff ?? null,
    is_retired: isRetired,
    is_system: classification === CLASSIFICATION.SYSTEM,
    is_active_staff: isActiveStaff,

    // ── Declared seat profile (the canonical ten) ─────────────────────────
    is_canonical_seat: isCanonicalSeat,
    staff_profile: profile
      ? {
          seat_label: profile.seat_label,
          provider_owner: profile.provider_owner,
          product_client: profile.product_client,
          capacity_class: profile.capacity_class,
          normal_host: profile.normal_host,
          harness: profile.harness,
          role_family: profile.role_family,
          herdr_seat_id: profile.herdr_seat_id,
        }
      : null,
    // Set only on non-canonical rows. Null means "belongs on the main surface".
    //
    // The Founder's authority level is passed in deliberately. `ali` and
    // `mustarq` are observed in the ledger and are not seats, so without this
    // they would carry the generic "historical / ghost" reason — which asserts
    // that the Founder used to be on this floor. They sit above it instead.
    suppression_reason: suppressionReasonFor({
      handle,
      isCanonicalSeat,
      isRetired,
      isSystem: classification === CLASSIFICATION.SYSTEM,
      authorityLevel: identity?.authority_level ?? null,
    }),
    suppressed_from_main_staff_surface: !isCanonicalSeat,
    herdr,
    herdr_host_conflict: herdrHostConflict,

    // ── Execution state, forwarded verbatim ───────────────────────────────
    current_state: agent.current_state,
    current_state_confidence: agent.current_state_confidence,
    activity_freshness: agent.activity_freshness,
    last_activity_at: agent.last_activity_at,
    // The last Room sequence this handle is recorded in. Forwarded from the
    // activity projection — never computed from `now`, and never read back out
    // of the live ledger here. Hash disagreement is classified as projection
    // lag (valid prefix extension) or a blocking integrity failure, never
    // inferred into a live current-task.
    last_meaningful_seq: agent.last_broker_sequence ?? null,
    lifetime_events: agent.lifetime_events ?? 0,

    // Forwarded for contract completeness, under a name that says it was frozen
    // at ingest. The floor never renders it as live.
    hours_since_last_activity_at_ingest: agent.hours_since_last_activity_at_ingest ?? null,
    mentioned_task_count: agent.mentioned_task_count ?? 0,

    // ── The two current-task truths, side by side and unmerged ────────────
    execution_current_task: executionTask,
    execution_task_confidence: agent.current_task_confidence,
    execution_task_source: agent.current_task_source,
    execution_current_assignment: unknown(agent.current_assignment) ? null : agent.current_assignment,
    execution_assignment_confidence: agent.current_assignment_confidence,
    execution_assignment_source: agent.current_assignment_source,

    duty_state: staff?.duty_state ?? 'UNKNOWN',
    duty_current_task: dutyTask,
    duty_capacity_note: staff?.capacity_note ?? null,
    duty_capacity_reset_at: staff?.capacity_reset_at ?? null,
    duty_restrictions: staff?.restrictions ?? null,
    duty_last_updated_at: staff?.last_updated_at ?? null,
    duty_last_updated_by: staff?.last_updated_by ?? null,
    duty_evidence_count: staff?.evidence_count ?? 0,

    // A plain string inequality between two canonical values. It is reported,
    // never adjudicated — see the module header.
    truth_disagreement:
      executionTask && dutyTask
        ? {
            values_differ: executionTask !== dutyTask,
            execution_side: { source: 'activity.json', value: executionTask },
            duty_side: { source: 'staff-state.json', value: dutyTask },
            resolution: 'NOT RESOLVED BY COMMAND — both canonical values are rendered as recorded',
          }
        : null,

    // ── Session presence ──────────────────────────────────────────────────
    has_session: Boolean(session),
    session,
    has_duty_record: Boolean(staff),

    // ── Recorded conflicts ────────────────────────────────────────────────
    conflict_types: conflictTypes,
    has_conflict: conflictTypes.length > 0,
  };
}

/**
 * Assemble the Phase 3 floor payload from an already-built Phase 1/2 surface.
 *
 * Pure: it reads the surface, it does not touch the filesystem. Every value in
 * the result is either forwarded from the surface or a count/grouping over
 * forwarded values.
 */
export function buildFloor({ surface }) {
  const execution = surface.execution_truth ?? {};
  const agents = Array.isArray(execution.agents) ? execution.agents : [];
  const identities = surface.identities?.byHandle ?? {};
  const staff = surface.staff_state?.byHandle ?? {};
  const sessions = surface.sessions?.byHandle ?? {};
  const conflicts = Array.isArray(execution.conflicts) ? execution.conflicts : [];
  const events = Array.isArray(execution.activity_events) ? execution.activity_events : [];

  // The Herdr manifest join. `bySeatId` is read even when the manifest is
  // unavailable — it is then empty, and every seat reports the absence rather
  // than inheriting a launch fact it has no source for.
  const herdrManifest = surface.herdr_manifest ?? { available: false, bySeatId: {}, seats: [] };
  const herdrBySeatId = herdrManifest.bySeatId ?? {};

  // ── A. Staff roster ─────────────────────────────────────────────────────
  //
  // Conflict types are indexed by handle first so a roster row can show WHY it
  // is conflicted rather than merely that it is.
  const conflictsByHandle = new Map();
  for (const c of conflicts) {
    const handles = c.handles ?? (c.handle ? [c.handle] : []);
    for (const h of handles) {
      if (!conflictsByHandle.has(h)) conflictsByHandle.set(h, []);
      conflictsByHandle.get(h).push(c.type);
    }
  }

  const roster = agents.map((agent) => {
    const profile = isCanonicalStaffHandle(agent.handle) ? staffProfileFor(agent.handle) : null;
    const herdrSeat =
      profile?.herdr_seat_id && Object.hasOwn(herdrBySeatId, profile.herdr_seat_id)
        ? herdrBySeatId[profile.herdr_seat_id]
        : null;
    return buildRosterEntry({
      agent,
      identity: identities[agent.handle] ?? null,
      staff: staff[agent.handle] ?? null,
      session: sessions[agent.handle] ?? null,
      conflictTypes: conflictsByHandle.get(agent.handle) ?? [],
      herdrSeat,
    });
  });

  const rosterByHandle = new Map(roster.map((r) => [r.handle, r]));

  // ── A2. The curated Dev Studio staff surface ─────────────────────────────
  //
  // The ten, in the Founder's declared order, each joined to its ledger row.
  //
  // A canonical seat with NO row in the execution ledger still appears, with
  // `observed_in_ledger: false` and every execution field UNKNOWN. Omitting it
  // would make "this seat exists and has said nothing" indistinguishable from
  // "this seat does not exist", and the second reading is the one that quietly
  // deletes people from a floor.
  const canonicalSeatHandles = new Set(CANONICAL_STAFF_HANDLES);
  const canonicalSeats = STAFF_PROFILE.map((profile) => {
    const row = rosterByHandle.get(profile.handle) ?? null;
    if (row) {
      return { ...row, observed_in_ledger: true };
    }
    // Present in the declared profile, absent from the projection. Every
    // execution-side field is UNKNOWN rather than null-with-no-explanation, and
    // no identity, duty, session or assignment is invented for it.
    return {
      handle: profile.handle,
      identity_present: false,
      identity_status: 'UNKNOWN',
      display_name: null,
      role: null,
      authority_level: null,
      is_legacy: false,
      is_revoked: false,
      staff_classification: 'UNKNOWN',
      counts_as_active_staff: null,
      is_retired: false,
      is_system: false,
      is_active_staff: false,
      is_canonical_seat: true,
      staff_profile: {
        seat_label: profile.seat_label,
        provider_owner: profile.provider_owner,
        product_client: profile.product_client,
        capacity_class: profile.capacity_class,
        normal_host: profile.normal_host,
        harness: profile.harness,
        role_family: profile.role_family,
        herdr_seat_id: profile.herdr_seat_id,
      },
      suppression_reason: null,
      suppressed_from_main_staff_surface: false,
      herdr: null,
      herdr_host_conflict: false,
      current_state: 'UNKNOWN',
      current_state_confidence: 'UNKNOWN',
      activity_freshness: 'UNKNOWN',
      last_activity_at: null,
      last_meaningful_seq: null,
      lifetime_events: 0,
      hours_since_last_activity_at_ingest: null,
      mentioned_task_count: 0,
      execution_current_task: null,
      execution_task_confidence: 'UNKNOWN',
      execution_task_source: null,
      execution_current_assignment: null,
      execution_assignment_confidence: 'UNKNOWN',
      execution_assignment_source: null,
      duty_state: 'UNKNOWN',
      duty_current_task: null,
      duty_capacity_note: null,
      duty_capacity_reset_at: null,
      duty_restrictions: null,
      duty_last_updated_at: null,
      duty_last_updated_by: null,
      duty_evidence_count: 0,
      truth_disagreement: null,
      has_session: false,
      session: null,
      has_duty_record: false,
      conflict_types: [],
      has_conflict: false,
      observed_in_ledger: false,
      absence_reason:
        'DECLARED SEAT, NOT OBSERVED — this handle has no row in the current activity projection. Every execution value is UNKNOWN; none is inferred.',
    };
  });

  // ── Herdr join for the placeholder rows ──────────────────────────────────
  //
  // The block above deliberately leaves `herdr: null` so that a canonical seat
  // with no ledger row cannot inherit a launch fact that was joined from a row
  // that does not exist. The manifest join is independent of the ledger, so it
  // is applied here, keyed only on the declared seat id.
  //
  // A seat that declares NO seat id at all (`copilot`, `opencode`) still gets a
  // join object. Leaving it null would put the two absent cases — "no manifest
  // row for the id we named" and "this seat names no id" — into the same null,
  // and the board would report one of them as unknown and the other as
  // invisible. They are different facts and both are stated.
  for (const seat of canonicalSeats) {
    if (seat.herdr) continue;
    const seatId = seat.staff_profile?.herdr_seat_id ?? null;
    const herdrSeat = seatId && Object.hasOwn(herdrBySeatId, seatId) ? herdrBySeatId[seatId] : null;
    if (herdrSeat) {
      seat.herdr = {
        declared: true,
        seat_id: herdrSeat.seat_id,
        declared_runtime: herdrSeat.declared_runtime,
        launchable: herdrSeat.launchable,
        startup_policy: herdrSeat.startup_policy,
        terminal: herdrSeat.terminal,
        executable_present: herdrSeat.executable_present,
        identity_probe: herdrSeat.identity_probe,
        herdr_kind: herdrSeat.herdr_kind,
        evidence: herdrSeat.evidence,
      };
      seat.herdr_host_conflict =
        String(herdrSeat.declared_runtime).toUpperCase() !==
        String(seat.staff_profile.normal_host).toUpperCase();
    } else {
      seat.herdr = {
        declared: false,
        seat_id: seatId,
        declared_runtime: null,
        launchable: null,
        startup_policy: null,
        terminal: null,
        executable_present: null,
        identity_probe: null,
        herdr_kind: null,
        evidence: null,
        absent_reason: seatId
          ? `the Herdr manifest declares no row for seat id "${seatId}"`
          : 'the staff profile declares no Herdr seat id for this handle',
      };
    }
  }

  const suppressed = roster
    .filter((r) => r.suppressed_from_main_staff_surface)
    .map((r) => ({
      handle: r.handle,
      reason: r.suppression_reason,
      staff_classification: r.staff_classification,
      identity_status: r.identity_status,
      is_retired: r.is_retired,
      is_system: r.is_system,
      last_meaningful_seq: r.last_meaningful_seq,
    }));

  // A canonical handle observed in the ledger but absent from the profile would
  // be a drift in the declared roster. It is counted so the drift is visible,
  // not so it can be corrected here.
  const observedButUndeclared = roster
    .filter((r) => !canonicalSeatHandles.has(r.handle))
    .map((r) => r.handle);

  const staffBlock = {
    authority: STAFF_PROFILE_AUTHORITY,
    declared_handles: [...CANONICAL_STAFF_HANDLES],
    canonical_seats: canonicalSeats,
    canonical_count: canonicalSeats.length,
    observed_in_ledger: canonicalSeats.filter((s) => s.observed_in_ledger).length,
    declared_not_observed: canonicalSeats
      .filter((s) => !s.observed_in_ledger)
      .map((s) => s.handle),
    suppressed,
    suppressed_count: suppressed.length,
    // Every observed handle is accounted for: canonical or suppressed. If these
    // two ever stop summing to `rosterCounts.observed`, a handle is being
    // dropped somewhere and the payload says so instead of hiding it.
    accounting:
      canonicalSeats.filter((s) => s.observed_in_ledger).length + suppressed.length ===
      roster.length
        ? 'COMPLETE — every observed handle is either a declared seat or listed as suppressed'
        : 'INCOMPLETE — observed handles do not reconcile against declared plus suppressed; treat this as a defect',
    observed_but_undeclared: observedButUndeclared,

    // ── Session / turn join, from identity leases ──────────────────────────
    //
    // "Who has the turn" is asked on this board, and the honest answer from a
    // lease is narrower than the question. A lease says a handle is HELD by a
    // session instance. It does not say that session is mid-task, and it does
    // not pick one holder out of several.
    //
    // So this reports every declared seat holding a lease and states plainly
    // that the turn is not derivable. Naming a single turn-holder here would be
    // Command deciding who is working, from presence, which is exactly the
    // inference this product exists to refuse.
    session_leases: {
      holders: canonicalSeats
        .filter((s) => s.has_session)
        .map((s) => ({
          handle: s.handle,
          instance_id: s.session?.instance_id ?? null,
          hostname: s.session?.hostname ?? null,
          claimed_at: s.session?.claimed_at ?? null,
          last_seen_at: s.session?.last_seen_at ?? null,
        })),
      holders_count: canonicalSeats.filter((s) => s.has_session).length,
      turn_holder: 'UNKNOWN',
      turn_holder_reason:
        'NOT DERIVABLE FROM A LEASE — a lease records that a handle is held by a session instance. It is presence, not activity, and it does not establish who is mid-task. Command does not pick a winner among lease holders.',
      source: CANONICAL.identityLeases,
    },

    roster_still_complete: true,
    roster_completeness_note:
      'floor.roster.entries is UNCHANGED and still contains every observed handle. The main staff surface is curated; the roster is not. Nothing was deleted to make the board look right.',
    herdr_manifest: {
      available: herdrManifest.available ?? false,
      state: herdrManifest.state ?? 'UNAVAILABLE',
      reason: herdrManifest.reason ?? null,
      path: herdrManifest.path ?? null,
      authority: herdrManifest.authority ?? 'UNAVAILABLE',
      seat_count: herdrManifest.count ?? 0,
      meaning: herdrManifest.meaning ?? null,
      live_state_source: herdrManifest.live_state_source ?? null,
      live_state_note: herdrManifest.live_state_note ?? null,
    },
  };

  const rosterCounts = {
    observed: roster.length,
    active_staff: roster.filter((r) => r.is_active_staff).length,
    retired: roster.filter((r) => r.is_retired).length,
    system: roster.filter((r) => r.is_system).length,
    // An agent in the execution ledger with NO canonical identity record. It is
    // counted separately because it is the population most likely to be
    // misread as staff.
    unknown_identity: roster.filter((r) => !r.identity_present).length,
    conflicted: roster.filter((r) => r.has_conflict).length,
    with_duty_record: roster.filter((r) => r.has_duty_record).length,
    with_session: roster.filter((r) => r.has_session).length,
    execution_and_duty_both_present: roster.filter(
      (r) => r.execution_current_task && r.duty_current_task,
    ).length,
    truth_disagreements: roster.filter(
      (r) => r.truth_disagreement && r.truth_disagreement.values_differ,
    ).length,
    // Curation counts. Separate from `observed` on purpose: `observed` is what
    // the ledger holds, these are what the board shows.
    canonical_seats: staffBlock.canonical_count,
    canonical_observed: staffBlock.observed_in_ledger,
    canonical_not_observed: staffBlock.declared_not_observed.length,
    suppressed: staffBlock.suppressed_count,
    herdr_host_conflicts: canonicalSeats.filter((s) => s.herdr_host_conflict).length,
    herdr_seats_without_manifest_row: canonicalSeats.filter(
      (s) => s.staff_profile && s.herdr && s.herdr.declared === false,
    ).length,
  };

  // This is a separate glance projection, not part of the identity census.
  // It is assembled from the two declared status fields only; the renderer
  // receives these buckets and never classifies roster rows itself. A missing
  // execution source is not a verified empty roster: publish no buckets until
  // the source explicitly declares itself available. An available source with
  // zero agents still produces six measured zeroes.
  const staffGlanceCounts =
    execution.available === true && execution.roster_input_available === true
      ? computeStaffGlanceCounts(roster)
      : undefined;

  // ── C. Meaningful activity ──────────────────────────────────────────────
  //
  // Newest first. Ordering is presentation; the filter is the judgement, and it
  // is exactly the four canonical flags and nothing else.
  const signalEvents = events.filter(carriesSignal).sort((a, b) => {
    const sa = a.broker_sequence ?? -1;
    const sb = b.broker_sequence ?? -1;
    if (sa !== sb) return sb - sa;
    return String(b.created_at ?? '').localeCompare(String(a.created_at ?? ''));
  });

  const sequences = events.map((e) => e.broker_sequence).filter((s) => typeof s === 'number');

  // Signal loss is measured, not asserted: every signal-bearing event that
  // entered the window must survive into the feed. If this is ever non-zero the
  // floor has hidden evidence and that is a defect, not a filter tuning choice.
  const signalInWindow = events.filter(carriesSignal).length;
  const signalLoss = signalInWindow - signalEvents.length;

  const activity = {
    window: {
      size: events.length,
      broker_sequence_min: sequences.length ? Math.min(...sequences) : null,
      broker_sequence_max: sequences.length ? Math.max(...sequences) : null,
      source: execution.ledger?.records_total != null ? 'activity.json activity_events window' : 'UNKNOWN',
    },
    filter: {
      rule: 'an event is shown when it carries at least one canonical signal flag',
      signal_flags: [...SIGNAL_FLAGS],
      window_total: events.length,
      signal_total: signalInWindow,
      shown: signalEvents.length,
      filtered_out: events.length - signalEvents.length,
      signal_loss: signalLoss,
      // Stated so a reader can check the filter rather than trust it.
      guarantee:
        signalLoss === 0
          ? 'every signal-bearing event in the window survives into the feed'
          : 'SIGNAL LOSS DETECTED — the feed is not showing everything canonical flagged',
    },
    // Provenance travels with every row. A feed entry without body_sha and
    // record_hash is a claim; with them, it is evidence.
    events: signalEvents.map((e) => ({
      event_id: e.event_id,
      broker_sequence: e.broker_sequence,
      created_at: e.created_at,
      handle: e.agent?.handle ?? 'UNKNOWN',
      // Absent canonical fields are rendered UNKNOWN by the UI, never inferred.
      action: e.action ?? null,
      action_confidence: e.action_confidence ?? 'UNKNOWN',
      task: e.task ?? null,
      state: e.state,
      state_confidence: e.state_confidence ?? 'UNKNOWN',
      project: e.project ?? null,
      // Forwarded as context, explicitly labelled as activity-against a family
      // and NOT a maturity input. `process_stage` is not carried at all: it is
      // null on every event in the live window, and forwarding it would invite
      // exactly the activity-reads-as-maturity confusion the surface exists to
      // prevent.
      process_family_context: e.process_family ?? null,
      has_evidence: e.has_evidence === true,
      is_blocker: e.is_blocker === true,
      is_handoff: e.is_handoff === true,
      needs_founder: e.needs_founder === true,
      serp_refs: e.serp_refs ?? [],
      mentions: e.mentions ?? [],
      body_sha: e.body_sha ?? null,
      record_hash: e.record_hash ?? null,
      source: e.source ?? null,
    })),
  };

  // ── B. Assignments ──────────────────────────────────────────────────────
  //
  // A separate array from the roster because it answers a different question
  // and carries a different truth. Assignments are the EXECUTION side only.
  // The duty side lives on the roster row and is never folded in here.
  //
  // `mentioned_task_count` travels as a count and is named as a mention count.
  // It is never an assignment, and no mention id list is forwarded.
  const assignments = roster.map((r) => ({
    handle: r.handle,
    display_name: r.display_name,
    identity_present: r.identity_present,
    current_assignment: r.execution_current_assignment,
    assignment_confidence: r.execution_assignment_confidence,
    assignment_source: r.execution_assignment_source,
    current_task: r.execution_current_task,
    task_confidence: r.execution_task_confidence,
    task_source: r.execution_task_source,
    // Named for what it is. The UI renders it inside a panel whose heading says
    // these are mentions, and never adjacent to an assignment value.
    mention_count: r.mentioned_task_count,
    mention_note: 'Mentioned in the ledger. A mention is not an assignment and is not work in progress.',
    last_activity_at: r.last_activity_at,
    is_retired: r.is_retired,
    truth_disagreement: r.truth_disagreement,
  }));

  // ── E. Constraints rail ─────────────────────────────────────────────────
  const constraints = [];

  for (const c of conflicts) {
    constraints.push({
      kind: 'IDENTITY_CONFLICT',
      subject: c.handles?.join(' / ') ?? c.handle ?? 'UNKNOWN',
      detail: c.detail,
      canonical_source: 'activity.json conflicts[]',
      resolution: 'SURFACED, NEVER MERGED — Command does not reconcile identity',
    });
  }

  for (const r of roster.filter((x) => !x.identity_present)) {
    constraints.push({
      kind: 'UNKNOWN_IDENTITY',
      subject: r.handle,
      detail:
        'Observed in the execution ledger with no entry in the canonical identity registry. Identity is UNKNOWN.',
      canonical_source: 'agent-comms/protocol/v1/identities.json',
      resolution: 'NOT INFERED — no identity is invented, merged or fabricated for this handle',
    });
  }

  for (const r of roster.filter((x) => x.identity_revoked)) {
    constraints.push({
      kind: 'REVOKED_IDENTITY',
      subject: r.handle,
      detail: 'The canonical identity registry records a revocation for this handle.',
      canonical_source: 'agent-comms/protocol/v1/identities.json',
      resolution: 'SURFACED — revocation is not treated as active staff',
    });
  }

  if (execution.ledger?.lag === true) {
    constraints.push({
      kind: 'PROJECTION_LAG',
      subject: 'activity.json',
      detail:
        execution.reason ??
        'The Room ledger has a verified append-only extension beyond the activity checkpoint.',
      canonical_source: 'agent-comms/room.jsonl vs activity.json',
      resolution: `Visible lag only — not corruption and not a Command health blocker. Refresh remains the existing control-board producer ingest_room_activity.py --watch (exclusive writer). Command HTTP/buildSurface() never ingest. Projection generated_at: ${execution.generated_at ?? 'UNKNOWN'}.`,
    });
  } else if (execution.state === 'STALE') {
    constraints.push({
      kind: 'STALE_EXECUTION_PROJECTION',
      subject: 'activity.json',
      detail:
        execution.reason ??
        'The Room ledger has moved since this projection was generated.',
      canonical_source: 'agent-comms/room.jsonl vs activity.json',
      resolution: `Regeneration is required and is NOT performed by Command (read-only). Run ingest_room_activity.py in the control board. Projection generated_at: ${execution.generated_at ?? 'UNKNOWN'}. Recorded ledger ${execution.ledger?.recorded_sha256_prefix ?? 'UNKNOWN'} vs live ${execution.ledger?.live_sha256_prefix ?? 'UNKNOWN'}.`,
    });
  }

  for (const r of roster.filter((x) => x.truth_disagreement?.values_differ)) {
    constraints.push({
      kind: 'TRUTH_DISAGREEMENT',
      subject: r.handle,
      detail: `activity.json records "${r.execution_current_task}" while staff-state.json records a different duty-side value.`,
      canonical_source: 'activity.json vs agent-comms/protocol/v1/staff-state.json',
      resolution: 'BOTH RENDERED WITH PROVENANCE — Command does not choose or merge them',
    });
  }

  // ── Seat-profile curation constraints ────────────────────────────────────
  //
  // Three new facts the main staff surface now depends on, each of which can be
  // wrong in a way that would silently mislead an operator. All three are
  // reported rather than repaired.

  // 1. The Herdr manifest could not be read. Without it every seat loses its
  //    launchability and declared runtime, and a board that silently drops those
  //    columns reads exactly like a board where nobody is launchable.
  if (!(herdrManifest.available ?? false)) {
    constraints.push({
      kind: 'HERDR_MANIFEST_UNAVAILABLE',
      subject: herdrManifest.path ?? 'herdr-floor/manifest.json',
      detail:
        herdrManifest.reason ??
        'The Herdr Floor launch manifest could not be read, so no seat reports a declared launch runtime or launchability.',
      canonical_source: CANONICAL_HERDR_MANIFEST,
      resolution:
        'REPORTED AS ABSENT — launchability is shown as unknown for every seat. It is never assumed false and never inferred from the manifest that could not be read.',
    });
  }

  // 2. A declared seat's normal host disagrees with the runtime its manifest
  //    launches. Elder is the live case (Founder roster: WSL; manifest:
  //    windows). This is a Founder decision and is deliberately unanswered here.
  for (const s of canonicalSeats.filter((x) => x.herdr_host_conflict)) {
    constraints.push({
      kind: 'HERDR_HOST_CONFLICT',
      subject: s.handle,
      detail: `The declared seat profile records normal host "${s.staff_profile.normal_host}" while the Herdr manifest declares launch runtime "${s.herdr.declared_runtime}" for seat id "${s.herdr.seat_id}".`,
      canonical_source: `server/staff-profile.mjs vs ${CANONICAL_HERDR_MANIFEST}`,
      resolution:
        'BOTH VALUES RENDERED WITH PROVENANCE — NOT RESOLVED BY COMMAND. Which is canonical is a Founder decision; no line in this package is entitled to make it.',
    });
  }

  // 3. A canonical seat declares no Herdr manifest row, so it has no launch
  //    policy and no launchability. Absence, not a refusal.
  for (const s of canonicalSeats.filter((x) => x.herdr && x.herdr.declared === false)) {
    constraints.push({
      kind: 'NO_HERDR_MANIFEST_ROW',
      subject: s.handle,
      detail: s.herdr.absent_reason ?? 'the Herdr manifest declares no row for this seat',
      canonical_source: CANONICAL_HERDR_MANIFEST,
      resolution:
        'REPORTED AS ABSENT — no seat id, launch policy or launchability is invented for this seat. Herdr join is read-only.',
    });
  }

  // 4. A declared seat exists in the profile but has said nothing in the
  //    projection. Present, but with UNKNOWN everywhere, never dropped.
  for (const s of canonicalSeats.filter((x) => x.observed_in_ledger === false)) {
    constraints.push({
      kind: 'DECLARED_SEAT_NOT_OBSERVED',
      subject: s.handle,
      detail:
        s.absence_reason ??
        'This handle is a declared Dev Studio seat but has no row in the current activity projection.',
      canonical_source: 'server/staff-profile.mjs vs activity.json',
      resolution:
        'RENDERED WITH UNKNOWN EVERYWHERE — the seat stays on the board. Its execution values are not inferred, and its absence is not read as a retirement.',
    });
  }

  // 5. The curation arithmetic does not reconcile. If this ever fires, a handle
  //    is being dropped and the payload says so instead of hiding it.
  if (!staffBlock.accounting.startsWith('COMPLETE')) {
    constraints.push({
      kind: 'STAFF_ACCOUNTING_INCOMPLETE',
      subject: 'staff roster',
      detail: `${staffBlock.observed_in_ledger} declared-and-observed plus ${staffBlock.suppressed_count} suppressed does not reconcile against ${roster.length} observed handles.`,
      canonical_source: 'server/floor.mjs staff block',
      resolution:
        'REPORTED AS A DEFECT — an observed handle is neither a declared seat nor listed as suppressed. It is not resolved here.',
    });
  }

  // ── D. Session / runtime liveness ───────────────────────────────────────
  //
  // Runtime is forwarded from the Phase 2 health floor. Phase 3 does not measure
  // runtime a second time; two measurements of one host would be one more
  // number that could disagree with another.
  const runtimeDimension =
    surface.health_floor?.current_health?.find((d) => d.id === 'runtime') ?? null;

  return {
    phase: 3,
    name: 'Dev Studio Floor',
    authority: 'DERIVED_PROJECTION',
    is_ssot: false,
    access: 'READ_ONLY',
    generated_at: new Date().toISOString(),

    // The staleness declaration is a top-level field, not a footnote. Every
    // execution value on this surface was true as of this timestamp.
    execution_projection: {
      generated_at: execution.generated_at ?? null,
      state: execution.state ?? 'UNKNOWN',
      reason: execution.reason ?? null,
      authority: execution.authority ?? 'UNKNOWN',
      not_a_new_ssoT: execution.not_a_new_ssoT ?? null,
      ledger: execution.ledger ?? null,
      ingest_performed_by_command: false,
      ingest_note:
        'Command never re-ingests. The activity projection is regenerated by the control board, which writes to canonical state and is therefore out of scope for a read-only surface.',
    },

    roster: { entries: roster, counts: rosterCounts },
    ...(staffGlanceCounts ? { staff_glance_counts: staffGlanceCounts } : {}),

    // The curated Dev Studio staff board. Attached alongside `roster`, never
    // merged into it: `roster` is the complete observed population and
    // `staff` is the declared ten plus a stated account of everything else.
    staff: staffBlock,

    assignments,
    activity,
    sessions: {
      available: surface.sessions?.available ?? false,
      state: surface.sessions?.state ?? 'UNAVAILABLE',
      reason: surface.sessions?.reason ?? null,
      count: surface.sessions?.count ?? 0,
      source: surface.sessions?.source ?? null,
      meaning:
        surface.sessions?.meaning ??
        'A lease records that a handle is held by a session instance. It is presence, not activity.',
      entries: roster
        .filter((r) => r.has_session)
        .map((r) => ({ handle: r.handle, ...r.session })),
      // Named explicitly so nobody reads the lease count as a headcount of
      // people currently working.
      not_a_measure_of_work: true,
    },

    runtime: runtimeDimension
      ? {
          state: runtimeDimension.state,
          detail: runtimeDimension.detail,
          node_version: runtimeDimension.node_version ?? null,
          platform: runtimeDimension.platform ?? null,
          uptime_seconds: runtimeDimension.uptime_seconds ?? null,
          measured_by: 'Phase 2 health floor (forwarded, not re-measured)',
        }
      : {
          state: 'UNKNOWN',
          detail: 'runtime dimension not present in the health floor',
          measured_by: 'Phase 2 health floor (forwarded, not re-measured)',
        },

    constraints,

    // ── What this surface deliberately does not carry ────────────────────
    //
    // Declared in the payload, not just in a comment, so a client — or the next
    // engineer — can tell the difference between "absent by ruling" and
    // "absent by oversight".
    excluded: {
      /*
        PROVIDER — the original ruling, preserved verbatim and still true.

        RULING 1 held that no canonical field carries an LLM provider for any
        agent or seat, and that it was dropped rather than inferred. That ruling
        is NOT being rewritten by the seat-profile work, and the text below is
        left exactly as it was so the record and the test that guards it stay
        honest: there is still no canonical provider field, and nothing infers
        one.

        What seq 8475 added is a different, narrower thing — a DECLARED
        provider/owner per seat, stated by the Founder, and carried under
        `declared_provider_metadata` below. A declaration is not a canonical
        provider field and it is not provider health. Keeping the two apart in
        the payload is what stops a declared string from quietly becoming
        evidence later.
      */
      provider_health: 'EXCLUDED BY FOUNDER RULING — no canonical provider field exists; not inferred',
      declared_provider_metadata:
        'PRESENT BY FOUNDER DECLARATION (Room seq 8475) — provider/owner, product/client, capacity class, normal host and role family are carried per declared seat on floor.staff.staff_profile, sourced from server/staff-profile.mjs. This is a DECLARATION, not a canonical field and not provider health. No live provider, model or billing telemetry exists for any harness and none is inferred.',
      live_model:
        'ABSENT BY RULING — no uniform live-model signal exists. Founder recorded that OpenCode, Pi and Goose vary by session. UNKNOWN beats a declared string that drifts.',
      usage_and_quota:
        'ABSENT BY RULING — no uniform provider billing API. usage stays manual, Founder-updated, in staff-state.json and is forwarded verbatim. No meter is synthesised beside it.',
      live_pid_and_process_state:
        'NOT IN THIS PAYLOAD BY DESIGN — runtime facts come from the Herdr broker projection (GET /api/herdr/state) at render time and are never persisted into a canonical read.',
      seat_registry_fleet:
        'NOT AUTHORITATIVE — src/schemas/seat-registry.ts CANONICAL_STARQ_FLEET is superseded by server/staff-profile.mjs and is not read by this package.',
      avatars: 'OUT OF PHASE 3 — the read-only raw surface is not widened to serve them',
      maturity_or_scoring: 'NOT PRESENT — this payload carries no maturity, score, weight or percentage',
      process_stage: 'NOT PRESENT — null on every event in the live window and structurally unjoinable to activity',
      handoff_ledger: 'NOT PRESENT — canonical source records an is_handoff flag only, not handoff records',
      erp_implementation: 'NOT PRESENT as a Dev Studio floor source — current decision: RESTART_AUTHORIZED under DEC-109; task execution must be established from ERP work records.',
    },
  };
}
