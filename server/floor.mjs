/**
 * STARQ // COMMAND — Phase 3, the Dev Studio Floor payload.
 *
 * WHAT THIS MODULE IS FOR
 *
 * Phase 1 proved the data is real. Phase 2 proved the control plane serving it
 * is healthy. Phase 3 answers the operational question the Founder actually
 * asks: **who is on the floor, what does canonical source say they are doing,
 * and what is the evidence that anything moved at all.**
 *
 * WHY THE ASSEMBLY LIVES HERE AND NOT IN REACT
 *
 * Every judgement this file makes is a *selection* or a *count* over values
 * that already exist canonically. None of it is business truth:
 *
 *   - a staff roster groups handles by their canonical classification
 *   - an activity feed selects events carrying a signal flag
 *   - a conflict rail lists conflicts the projection already recorded
 *
 * A component that did this itself would be one refactor away from also
 * *scoring* something, and the Phase 1/2 architecture guards exist precisely
 * because maturity computation in React is the failure mode this product is
 * built to prevent. So the floor is assembled here, the payload is the
 * contract, and `surfaces/floor.tsx` renders it and nothing else.
 *
 * WHAT THIS MODULE DELIBERATELY DOES NOT DO
 *
 *   - No maturity, scoring, weighting, capping or averaging. None. There is no
 *     percentage anywhere in this file.
 *   - No time arithmetic. `hours_since_last_activity` is frozen at ingest and
 *     is forwarded verbatim under a name that says so. The floor renders
 *     `last_activity_at` plus the projection's own `generated_at`. Nothing here
 *     subtracts a timestamp from `now`, because a recomputed age on a stale
 *     projection is a number that is wrong by exactly the projection's age.
 *   - No provider health. No canonical field carries an LLM provider for any
 *     agent or seat (verified: zero hits across `agent-comms/protocol/v1/*.json`
 *     in the 29 Sep 2026 survey). Founder ruled it dropped rather than inferred.
 *     Inferring one would be fabricating a fact, so it is simply absent.
 *   - No avatars. Out of Phase 3 by ruling; the read-only raw surface is not
 *     widened to serve them.
 *   - No ingest. The activity projection is regenerated by the control board's
 *     own `ingest_room_activity.py`, which writes to the control board. Command
 *     is read-only and stays read-only. It reports staleness and names the
 *     regeneration step instead of performing it.
 *
 * THE TWO `current_task` FIELDS ARE NOT MERGED
 *
 * `activity.json` and `staff-state.json` both carry a current-task value and
 * they disagree. Founder ruling: render both with explicit provenance and
 * preserve the disagreement. This module therefore reports a plain string
 * inequality — `values_differ` — and both values with their source. It does
 * NOT decide which is correct, because that is a Founder decision and no
 * algorithm here is entitled to make it.
 */

